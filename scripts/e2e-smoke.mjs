// Quick end-to-end walk: sign up → onboarding → dashboard → cycle → log a day. Screenshots in /tmp/shots.
import { chromium } from "@playwright/test";
const base = process.env.BASE ?? "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--enable-unsafe-swiftshader", "--use-angle=swiftshader", "--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && !m.text().includes("bad HTTP response code (404)") && errors.push(m.text()));
const email = `asha+${Date.now()}@example.com`;
await page.goto(`${base}/auth?mode=create`);
await page.getByLabel("Your first name").fill("Asha");
await page.getByLabel("Email").fill(email);
await page.getByLabel("Password", { exact: true }).fill("a calm walk home");
await page.getByRole("checkbox").check();
await page.getByRole("button", { name: "Create account" }).last().click();
await page.waitForURL("**/onboarding", { timeout: 20000 });
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("switch", { name: /Chat with Mochi/ }).click();
await page.screenshot({ path: "/tmp/shots/onboarding-privacy.png" });
await page.getByRole("button", { name: "Continue" }).click();
const start = new Date(Date.now() - 20 * 86400000).toLocaleDateString("en-CA");
await page.getByLabel("When did your last period start?").fill(start);
await page.getByLabel("Usual cycle length (days)").fill("29");
await page.getByRole("button", { name: "Finish" }).click();
await page.waitForURL("**/dashboard", { timeout: 20000 });
await page.waitForTimeout(800);
await page.screenshot({ path: "/tmp/shots/dashboard.png" });
await page.goto(`${base}/cycle`);
await page.waitForTimeout(800);
await page.screenshot({ path: "/tmp/shots/cycle.png", fullPage: true });
await page.getByRole("button", { name: "Log today" }).click();
await page.getByRole("radio", { name: "Light" }).click();
await page.getByRole("button", { name: "Tired" }).click();
await page.screenshot({ path: "/tmp/shots/day-sheet.png" });
await page.getByRole("button", { name: "Save" }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: "/tmp/shots/cycle-after.png" });
console.log("email", email);
console.log(errors.length ? "ERRORS:\n" + errors.join("\n") : "no page errors");
await browser.close();
